def ingest(cards: list[dict]) -> int:
    titles = {c.get("title") for c in learn.list_cards(limit=500)}
    added = 0
    for s in cards:
        if s["title"] in titles:
            continue
        card = learn.add_card(body=s["body"], title=s["title"], source="all_variables")
        cid = card.get("id")
        if not isinstance(cid, int):
            continue
        learn.confirm_card(cid)
        store = learn.load_store()
        for c in store.get("cards") or []:
            if isinstance(c, dict) and c.get("id") == cid:
                wiki.save_saju_card_to_knowledge(c)
                break
        titles.add(s["title"])
        added += 1
    return added


def main() -> int:
    pool = build_all_variable_cards()
    added = ingest(pool)
    pack = learn.export_pack()
    st = learn.stats()
    print(f"pool={len(pool)} new_confirmed={added} total={st['total']} pack={pack.get('card_count')}")
    return 0


