from saju_card_reverify_enrich import FOOTER_MARK, STANDARD_FOOTER, _caution, _rich_saju_palja_section

_CAUTION_BLOCK = " " + _caution()
_FOOTER = (
    STANDARD_FOOTER
    if FOOTER_MARK in STANDARD_FOOTER
    else (
        " 본 내용은 명리 참고용이며 확정 예언·의학·법률·투자 자문이 아닙니다. "
        "가능성·경향으로 해석하며, 학파·환경에 따라 달라질 수 있습니다."
    )
)


def _finish(body: str) -> str:
    out = body.strip()
    if "【주의】" not in out:
        out += _CAUTION_BLOCK
    if FOOTER_MARK not in out:
        out = out.rstrip("。. ") + _FOOTER
    return out[:24000]


