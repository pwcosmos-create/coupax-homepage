        "<figure class=\"post-image\">\n"
        f"  <img src=\"{image_url}\" alt=\"{title} 관련 대표 이미지\" loading=\"lazy\">\n"
        f"  <figcaption>{category} 실전 가이드 대표 이미지</figcaption>\n"
