def _ingest(cards: list[dict], source: str) -> int:
    titles = {c.get("title") for c in learn.list_cards(limit=200)}
    added = 0
    for s in cards:
        if s["title"] in titles:
            continue
        card = learn.add_card(body=s["body"], title=s["title"], source=source)
        cid = card.get("id")
        if isinstance(cid, int):
            learn.confirm_card(cid)
            store = learn.load_store()
            for c in store.get("cards") or []:
                if isinstance(c, dict) and c.get("id") == cid:
                    wiki.save_saju_card_to_knowledge(c)
                    break
            titles.add(s["title"])
            added += 1
    return added


def main() -> int:
    added = _ingest(NEW_CARDS, "cards_continue")
    pack = learn.export_pack()
    st = learn.stats()
    print(f"new_confirmed={added} total={st['total']} pack={pack.get('card_count')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
